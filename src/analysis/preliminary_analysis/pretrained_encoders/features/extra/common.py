"""新しい特徴量の共通の部品（design.md §13.2）。

- Change を 1 度だけ読んで、特徴量に要る事実（版・メッセージ・投票・CI の結果など）に整理する（ChangeFacts）
- コミットメッセージの末尾のトレーラーを除く（Git の git-interpret-trailers の決まり）
- 語数（空白で区切った数）

どの特徴量も「予測の時点 t までの記録だけ」で作る（design.md §11・§12.4）。そのため、版とメッセージは
時刻つきで持ち、t で切って使う（revisions_until・messages_until）。
"""
from __future__ import annotations

import bisect
import re
from dataclasses import dataclass, field
from datetime import datetime

from src.analysis.background_problem.common.time_utils import parse_dt
from src.analysis.preliminary_analysis.pretrained_encoders.features.extra import repo_rules
from src.analysis.preliminary_analysis.pretrained_encoders.utils import review_utils
from src.utils.bot_detection import BotDetector, is_auto_record, is_owner, votes_of

# Gerrit の特別なファイル（ファイルの一覧から除く。design.md §13.2）
MAGIC_FILES = {"/COMMIT_MSG", "/MERGE_LIST", "/PATCHSET_LEVEL"}

# 投票の読み方は src/utils/bot_detection.py の votes_of（数字の形と、古い形式の既定の文。2026-10-16 に移した）
# 行ごとのコメントの数（メッセージの "(N comments)"・"(1 comment)"）
_INLINE_RE = re.compile(r"\((\d+) (?:inline )?comments?\)")
# 復活（Qt の後回しからの再開 Reopened も含める。design.md §13.5 W20）・放棄・マージの記録の 1 行目
_RESTORE_RE = re.compile(r"^((Patch Set \d+:\s*)?Restored|Reopened)")
_ABANDON_RE = re.compile(r"^(Patch Set \d+:\s*)?Abandoned")
# Qt の後回し（前置きの付かない形だけ。design.md §11.1）
_DEFER_RE = re.compile(r"^Deferred")
# マージの記録（Gerrit 本体の文。source_check7 §4）
_MERGE_RE = re.compile(r"^Change has been successfully (?:merged|cherry-picked(?: as |\s*$)|rebased and submitted as |pushed)")


# ── 語数・トレーラー ─────────────────────────────────────
def word_count(text: str) -> int:
    """空白（スペース・改行など）で区切った語の数（design.md §13.2）。"""
    return len((text or "").split())


_TRAILER_LINE_RE = re.compile(r"^[A-Za-z0-9-]+[ \t]*:(.*)$")
_DIVIDER_RE = re.compile(r"^---(?: |$)")


def _is_trailer_line(line: str) -> bool:
    m = _TRAILER_LINE_RE.match(line)
    if not m:
        return False
    # 区切りの直後が空白なしで // なら URL とみなしてトレーラーにしない（説明書 OTHER RULES）
    return not m.group(1).startswith("//")


def strip_trailers(message: str) -> str:
    """コミットメッセージの末尾のトレーラーの塊を除いた本文を返す（design.md §13.3 message_word_count）。

    Git の説明書（git-interpret-trailers、2.56.0。data/feature_survey/source_check2_20261016.md）に沿う：
    - メッセージは末尾まで、ただし `---`（後ろが空白か行末）で始まる行があればその前まで
    - コメント行（# で始まる）は無視する
    - トレーラーの塊は、空行のあとに続く最後の行のまとまり。キー（英数字とハイフン）＋任意の空白・タブ＋`:`＋値
    - 行頭が空白の行は前のトレーラーの続き（RFC 822 の折り返し）
    - 値が空白なしで // から始まる行はトレーラーにしない（URL を誤って拾わないため）
    - 塊が「全部トレーラー」のときだけトレーラーとみなす。説明書のもう 1 つの条件（Git が作る／設定したトレーラーを含み
      25% 以上）は、Git が作るトレーラーが説明書に列挙されておらず、設定もしないので当てはめない
    """
    lines = (message or "").split("\n")
    for i, line in enumerate(lines):
        if _DIVIDER_RE.match(line):
            lines = lines[:i]
            break
    lines = [ln for ln in lines if not ln.startswith("#")]
    # 末尾の空行を落とし、最後の空行（段落の区切り）を探す
    end = len(lines)
    while end > 0 and not lines[end - 1].strip():
        end -= 1
    start = end
    while start > 0 and lines[start - 1].strip():
        start -= 1
    block = lines[start:end]
    if start == 0 or not block:
        return "\n".join(lines[:end])             # 空行の前がない（1 段落だけ）ならトレーラーの塊はない
    ok = bool(block) and _is_trailer_line(block[0])
    for ln in block[1:]:
        if ln[:1] in (" ", "\t"):
            continue                              # 前の行の続き
        if not _is_trailer_line(ln):
            ok = False
            break
    return "\n".join(lines[:start] if ok else lines[:end])


# ── Change の事実 ───────────────────────────────────────
@dataclass
class RevisionFact:
    number: int
    created: datetime
    sha: str
    parent_shas: list[str]
    files: dict[str, tuple[int, int, str]]   # パス -> (追加の行数, 削除の行数, 状態 A/D/M など)
    message: str                              # コミットメッセージ全体
    subject: str                              # 1 行目


@dataclass
class MessageFact:
    date: datetime
    author_id: object
    author_name: str
    is_bot: bool
    is_autogen: bool          # 自動の記録（bot_detection.is_auto_record。2026-10-16 改めた：印のないものも含む）
    is_owner: bool
    first_line: str
    text: str
    votes: list[tuple[str, int]]   # 1 行目の投票（名前, 値）。自動の記録の中の投票・古い形式の投票も含む（bot_detection.votes_of）
    inline_count: int
    ci_result: int | None          # 成功 1・失敗 0・CI の結果でなければ None（repo_rules.ci_result_of）
    is_restore: bool               # 復活（Qt の Reopened を含む）
    is_abandon: bool = False
    is_merge: bool = False         # マージの記録（印 autogenerated:gerrit:merged か、Gerrit 本体のマージの文）
    is_defer: bool = False         # Qt の後回し（Deferred。放棄と同じ状態の変更。design.md §13.4 D18）

    @property
    def is_human(self) -> bool:
        """人のコメント（design.md §13.2）：ボットと自動の記録を除いたメッセージ（作者を含む。作者を除くかは各特徴量で決める）。"""
        return not self.is_bot and not self.is_autogen


@dataclass
class ChangeFacts:
    number: int
    change_id: str
    owner_id: object
    owner_is_bot: bool
    branch: str
    created: datetime
    status: str
    merged_at: datetime | None
    closed_at: datetime | None          # 最後に閉じた時刻（マージか放棄。Open の期間の終わり）
    open_periods: list[tuple[datetime, datetime | None]]
    revisions: list[RevisionFact] = field(default_factory=list)   # 作成時刻の昇順
    messages: list[MessageFact] = field(default_factory=list)     # 日時の昇順
    _rev_times: list[datetime] = field(default_factory=list, repr=False)
    _msg_times: list[datetime] = field(default_factory=list, repr=False)

    def revisions_until(self, t: datetime) -> list[RevisionFact]:
        """t までに作られた版（t ちょうどを含む）。"""
        return self.revisions[:bisect.bisect_right(self._rev_times, t)]

    def latest_revision(self, t: datetime) -> RevisionFact | None:
        revs = self.revisions_until(t)
        return revs[-1] if revs else None

    def messages_until(self, t: datetime) -> list[MessageFact]:
        """t までのメッセージ（t ちょうどを含む）。"""
        return self.messages[:bisect.bisect_right(self._msg_times, t)]

    def is_open_at(self, t: datetime) -> bool:
        return review_utils.is_open_at(self.open_periods, t)


def _account_id(account: dict) -> object:
    if not isinstance(account, dict):
        return None
    return account.get("_account_id", account.get("email") or account.get("username") or account.get("name"))


def _files_of(rev: dict) -> dict[str, tuple[int, int, str]]:
    out = {}
    for path, info in (rev.get("files") or {}).items():
        if path in MAGIC_FILES:
            continue
        info = info or {}
        out[path] = (int(info.get("lines_inserted") or 0), int(info.get("lines_deleted") or 0),
                     str(info.get("status") or "M"))
    return out


def build_change_facts(change: dict, repo: str, detector: BotDetector) -> ChangeFacts | None:
    """Change の JSON から ChangeFacts を作る。作成時刻がなければ None。"""
    created = parse_dt(change.get("created"))
    if created is None:
        return None
    owner = change.get("owner") or {}
    periods = review_utils.open_periods(change)
    revs = []
    for sha, rev in (change.get("revisions") or {}).items():   # Gerrit の revisions はコミットの SHA がキー
        if not isinstance(rev, dict):
            continue
        rc = parse_dt(rev.get("created"))
        if rc is None:
            continue
        commit = rev.get("commit") or {}
        revs.append(RevisionFact(
            number=int(rev.get("_number") or 0), created=rc, sha=str(sha),
            parent_shas=[str(p.get("commit")) for p in (commit.get("parents") or []) if isinstance(p, dict)],
            files=_files_of(rev), message=str(commit.get("message") or ""),
            subject=str(commit.get("subject") or str(commit.get("message") or "").split("\n", 1)[0])))
    revs.sort(key=lambda r: (r.created, r.number))
    msgs = []
    for m in change.get("messages") or []:
        if not isinstance(m, dict):
            continue
        dt = parse_dt(m.get("date"))
        if dt is None:
            continue
        author = m.get("author") or {}
        text = str(m.get("message") or "")
        first = text.split("\n", 1)[0].strip()
        votes = votes_of(m)
        is_bot = detector.is_bot(author)
        tag = m.get("tag")
        inline = sum(int(n) for n in _INLINE_RE.findall(text))   # "(N comments)" は 2 行目以降に書かれる
        msgs.append(MessageFact(
            date=dt, author_id=_account_id(author), author_name=str(author.get("name") or ""),
            is_bot=is_bot, is_autogen=is_auto_record(m, detector.host),
            is_owner=is_owner(author, change), first_line=first, text=text, votes=votes,
            inline_count=inline,
            ci_result=repo_rules.ci_result_of(repo, str(author.get("name") or ""), is_bot, text, votes),
            is_restore=bool(_RESTORE_RE.match(first)),
            is_abandon=bool(_ABANDON_RE.match(first)),
            is_merge=(tag == "autogenerated:gerrit:merged") or bool(_MERGE_RE.match(first)),
            is_defer=bool(_DEFER_RE.match(first))))
    msgs.sort(key=lambda x: x.date)
    facts = ChangeFacts(
        number=int(change.get("change_number") or change.get("_number") or 0),
        change_id=str(change.get("change_id") or ""), owner_id=_account_id(owner),
        owner_is_bot=detector.is_bot(owner), branch=str(change.get("branch") or ""),
        created=created, status=str(change.get("status") or ""),
        merged_at=review_utils.merged_time(change),
        closed_at=(periods[-1][1] if periods else None), open_periods=periods,
        revisions=revs, messages=msgs)
    facts._rev_times = [r.created for r in revs]
    facts._msg_times = [m.date for m in msgs]
    return facts
