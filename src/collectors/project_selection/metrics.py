"""
第 3・第 4 段階：ボット一覧の作成と指標の算出（design.md §5.3, §6.4）

収集済みデータだけを使うので追加の通信は要らない。

ボットの判定は src/utils/bot_detection.py（設計書 src/utils/bot_detection.md）を使う。
第 3 段階で活動量の多いアカウントを出すのは、判定の決まり（§1 の ①〜③）で拾えない
機械のアカウントを見つけるため。これを人間として数えると、CI の投稿がレビューとして集計されてしまう。
"""

from __future__ import annotations

import json
import logging
import re
from collections import Counter
from pathlib import Path
from typing import Any, Dict, Iterator, List, Set

from src.collectors.project_selection import parallel
from src.collectors.project_selection.source_files import has_source
from src.config.path import DEFAULT_DATA_DIR
from src.utils.bot_detection import BotDetector, is_human_review_message

logger = logging.getLogger(__name__)

COLLECTED_DIR = DEFAULT_DATA_DIR / "openstack_collected"

# 版の投稿のときに自動で送られるメッセージ（design.md §5.7）。
# tag（autogenerated:）の付いていない古い形のものを除くため。
UPLOADED_PATCH_SET_PATTERN = re.compile(r"^Uploaded patch set")


def is_human_comment(message: Dict[str, Any], change: Dict[str, Any], detector: BotDetector) -> bool:
    """E2 で数える人間のコメントか（design.md §5.7）。

    正解ラベルと同じ決まり（autogenerated: の印・ボット・作成者本人を除く。bot_detection.md §3）に、
    版の投稿のときに自動で送られるメッセージを除く決まりを足したもの。
    """
    if not is_human_review_message(message, change, detector):
        return False
    return not UPLOADED_PATCH_SET_PATTERN.match((message.get("message") or "").strip())


def iter_changes(directory_name: str) -> Iterator[Dict[str, Any]]:
    """収集済みディレクトリの Change を 1 件ずつ読む。"""
    changes_dir = COLLECTED_DIR / directory_name / "changes"
    for path in changes_dir.glob("change_*.json"):
        try:
            with open(path, "r", encoding="utf-8") as f:
                yield json.load(f)
        except Exception:
            continue


def account_ranking(directory_name: str, detector: BotDetector,
                    limit: int = 50) -> List[Dict[str, Any]]:
    """アカウントごとの活動量を多い順に返す（第 3 段階の目視確認用）。

    ボットは活動量が突出するため、上位から公式資料と照合すれば
    一覧に載っていないものを見つけられる（design.md §5.3）。
    """
    created: Counter = Counter()
    posted: Counter = Counter()
    labels: Dict[str, Dict[str, Any]] = {}

    for change in iter_changes(directory_name):
        owner = change.get("owner") or {}
        key = (owner.get("email") or owner.get("name") or "").lower()
        if key:
            created[key] += 1
            labels.setdefault(key, owner)
        for message in change.get("messages") or []:
            author = message.get("author") or {}
            akey = (author.get("email") or author.get("name") or "").lower()
            if akey:
                posted[akey] += 1
                labels.setdefault(akey, author)

    rows = []
    for key in (created + posted).most_common(limit):
        identifier = key[0]
        account = labels.get(identifier, {})
        rows.append({
            "identifier": identifier,
            "name": account.get("name"),
            "created_changes": created.get(identifier, 0),
            "posted_messages": posted.get(identifier, 0),
            "judged_bot": detector.is_bot(account),
        })
    return rows


class RepositoryMetrics:
    """1 リポジトリ分の指標（design.md §6.4）。"""

    def __init__(self, repository: str):
        self.repository = repository
        self.changes = 0
        self.bot_changes = 0
        self.human_changes = 0
        self.human_comments = 0            # E2：人が作成した Change に付いた、人間のコメント（§5.7）
        self.revisions = 0
        self.reviewers: Counter = Counter()
        self.reviewed_changes = 0
        # 人間のコメントがついた Change ごとの、関わった人の集合（top10_reviewer_share 用。design.md §5.8）。
        # 上位 10 人は全部数え終わるまで決まらないので、最後まで持っておく
        self.reviewer_sets: List[frozenset] = []
        self.changes_with_source = 0       # E1：実装言語のファイルを含む Change
        self.broken = 0                    # 読めなかったファイルの数（指標には入れず、ログに出す）

    def add(self, change: Dict[str, Any], detector: BotDetector) -> None:
        self.changes += 1
        if has_source(change):
            self.changes_with_source += 1
        if detector.is_bot(change.get("owner")):
            self.bot_changes += 1
            return

        self.human_changes += 1
        self.revisions += len(change.get("revisions") or {})

        seen: Set[str] = set()
        for message in change.get("messages") or []:
            if not isinstance(message, dict) or not is_human_comment(message, change, detector):
                continue
            author = message.get("author") or {}
            self.human_comments += 1
            identifier = (author.get("email") or author.get("name") or "").lower()
            if identifier:
                seen.add(identifier)
        if seen:
            self.reviewed_changes += 1
            self.reviewers.update(seen)
            self.reviewer_sets.append(frozenset(seen))

    def merge(self, other: "RepositoryMetrics") -> None:
        """別に数えたかたまりの結果を足し合わせる（並列に読むため。design.md §4.4）。"""
        self.changes += other.changes
        self.bot_changes += other.bot_changes
        self.human_changes += other.human_changes
        self.human_comments += other.human_comments
        self.revisions += other.revisions
        self.reviewers.update(other.reviewers)
        self.reviewed_changes += other.reviewed_changes
        self.reviewer_sets.extend(other.reviewer_sets)
        self.changes_with_source += other.changes_with_source
        self.broken += other.broken

    def as_row(self) -> Dict[str, Any]:
        human = self.human_changes or 1
        reviewed = self.reviewed_changes or 1
        # 上位 10 人：関わった Change の数が多い順。同数のときは識別子の順で決める
        # （Counter.most_common は同数の並びが数えた順に左右され、並列に読むと結果が変わりうるため）
        ranked = sorted(self.reviewers.items(), key=lambda kv: (-kv[1], kv[0]))
        top10 = {r for r, _ in ranked[:10]}
        # 上位 10 人の誰か 1 人以上が関わった Change の割合。各 Change は 1 回だけ数える（design.md §5.8）
        top10_changes = sum(1 for s in self.reviewer_sets if not s.isdisjoint(top10))
        return {
            "repository": self.repository,
            "changes": self.changes,
            "bot_ratio": self.bot_changes / (self.changes or 1),
            "human_comments_per_change": self.human_comments / human,
            "revisions_per_change": self.revisions / human,
            "reviewers": len(self.reviewers),
            "reviewed_ratio": self.reviewed_changes / human,
            "source_ratio": self.changes_with_source / (self.changes or 1),
            "top10_reviewer_share": top10_changes / reviewed,
        }


def _compute_chunk(paths: List[Path], repository: str, detector: BotDetector,
                   period_start: str, period_end: str) -> RepositoryMetrics:
    """ファイルのかたまりを読み、対象期間に作成された Change の指標を数える。"""
    metrics = RepositoryMetrics(repository)
    for path in paths:
        try:
            with open(path, "r", encoding="utf-8") as f:
                change = json.load(f)
        except Exception:
            metrics.broken += 1
            continue
        created = (change.get("created") or "")[:10]
        if created and period_start <= created < period_end:
            metrics.add(change, detector)
    return metrics


def compute(directory_name: str, repository: str, detector: BotDetector,
            period_start: str, period_end: str, workers: int = 1) -> RepositoryMetrics:
    """収集済みデータから、対象期間に作成された Change の指標を出す。

    workers が 2 以上なら、ファイルをかたまりに分けて並列に読み、数えた結果を足し合わせる
    （design.md §4.4）。件数を足すだけなので、結果は 1 本で読んだ場合と同じ。
    """
    metrics = RepositoryMetrics(repository)
    paths = sorted((COLLECTED_DIR / directory_name / "changes").glob("change_*.json"))
    for part in parallel.map_files(repository, paths, _compute_chunk,
                                   (repository, detector, period_start, period_end), workers):
        metrics.merge(part)
    if metrics.broken:
        logger.warning(f"{repository}: 読めなかったファイルが {metrics.broken} 件ありました")
    logger.info(f"{repository}: {metrics.changes:,} 件から指標を算出しました")
    return metrics
