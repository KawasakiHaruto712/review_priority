"""ボットの判定（設計書：src/utils/bot_detection.md）。

アカウントは、次の ①〜④ のどれかに当てはまればボットとみなす（§1）。
  ① Gerrit の SERVICE_USER の印がある
  ② メールアドレスが gserviceaccount.com で終わる
  ③ name か display_name の最後の語が Bot・CI
  ④ 一覧ファイル（bot_accounts.csv）に載っている（ホスト必須。名前では照合しない）
"""
from __future__ import annotations

import csv
import logging
import re
from pathlib import Path
from urllib.parse import urlparse

from src.config.path import DEFAULT_CONFIG
from src.utils.constants import GERRIT_PROJECTS

logger = logging.getLogger(__name__)

BOT_ACCOUNTS_CSV = DEFAULT_CONFIG / "bot_accounts.csv"

# ③ 名前の最後の語（§1.3）
#   区切り（空白・_・-）のあとの ci / bot は大文字・小文字を区別しない
#   区切りがないときは、大文字の Bot / CI が小文字か数字の直後で終わるものだけ（Abbot・Talbot を拾わない）
SEP_PATTERN = re.compile(r"(?:^|[\s_\-])(ci|bot)$", re.IGNORECASE)
CAMEL_PATTERN = re.compile(r"[a-z0-9](Bot|CI)$")

SERVICE_USER_TAG = "SERVICE_USER"
GSERVICEACCOUNT_SUFFIX = "gserviceaccount.com"


def host_of(component: str) -> str:
    """GERRIT_PROJECTS[component]["host"] からホスト名を返す（スキームと /a を除く）。"""
    return urlparse(GERRIT_PROJECTS[component]["host"]).netloc


def name_says_bot(name: str | None) -> bool:
    """③ 名前の最後の語が Bot・CI か。"""
    if not name:
        return False
    name = str(name).strip()
    return bool(SEP_PATTERN.search(name) or CAMEL_PATTERN.search(name))


def _norm(value) -> str:
    return str(value).strip().lower() if value is not None else ""


def load_bot_accounts(host: str, accounts_csv: Path = BOT_ACCOUNTS_CSV) -> dict[str, set[str]]:
    """一覧ファイルから、host の行の account_id・username・email を読む（§2.2）。

    account_id は文字列のまま、username・email は小文字にして持つ。
    """
    ids: dict[str, set[str]] = {"account_id": set(), "username": set(), "email": set()}
    with open(accounts_csv, "r", encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            if (row.get("host") or "").strip() != host:
                continue
            account_id = (row.get("account_id") or "").strip()
            if account_id:
                ids["account_id"].add(account_id)
            for key in ("username", "email"):
                value = _norm(row.get(key))
                if value:
                    ids[key].add(value)
    return ids


class BotDetector:
    """1 つのホストのボット判定（§1）。一覧はホストで絞って読み込む。"""

    def __init__(self, host: str, accounts_csv: Path = BOT_ACCOUNTS_CSV):
        self.host = host
        self.listed = load_bot_accounts(host, accounts_csv)
        logger.info(f"ボット判定（{host}）：一覧の行の識別子 "
                    + ", ".join(f"{k} {len(v)}" for k, v in self.listed.items()))

    def reason(self, account: dict) -> str | None:
        """当てはまった決まり（"service_user" / "gserviceaccount" / "name" / "list"）。どれでもなければ None。"""
        if not isinstance(account, dict):
            return None
        if SERVICE_USER_TAG in (account.get("tags") or ()):
            return "service_user"
        if _norm(account.get("email")).endswith(GSERVICEACCOUNT_SUFFIX):
            return "gserviceaccount"
        if name_says_bot(account.get("name")) or name_says_bot(account.get("display_name")):
            return "name"
        account_id = account.get("_account_id")
        if account_id is not None and str(account_id) in self.listed["account_id"]:
            return "list"
        for key in ("username", "email"):
            value = _norm(account.get(key))
            if value and value in self.listed[key]:
                return "list"
        return None

    def is_bot(self, account: dict) -> bool:
        return self.reason(account) is not None


def is_owner(account: dict, change: dict) -> bool:
    """チケットの作成者本人か（_account_id → email → username/name の順）。"""
    owner = change.get("owner", {})
    if not isinstance(owner, dict) or not isinstance(account, dict):
        return False
    if owner.get("_account_id") is not None and account.get("_account_id") is not None:
        if owner["_account_id"] == account["_account_id"]:
            return True
    return any(owner.get(k) and account.get(k) and owner[k] == account[k]
               for k in ("email", "username", "name"))


def is_human_review_message(message: dict, change: dict, detector: BotDetector) -> bool:
    """§3 の決まりで、人間のレビューのメッセージか（自動の記録・ボット・作成者本人を除く）。

    2026-10-16 改めた：印 autogenerated: だけでなく、印のない自動の記録も除く（§3.1・§3.2。is_auto_record）。
    """
    if is_auto_record(message, detector.host):
        return False
    author = message.get("author", {})
    return not detector.is_bot(author) and not is_owner(author, change)


# ── 自動の記録（§3.1・§3.2。2026-10-16 追加） ─────────────────────
QT_HOST = "codereview.qt-project.org"
_PS_PREFIX = re.compile(r"^Patch Set \d+:\s*")

# Gerrit 本体の文（先頭一致）。source_check7 §4・source_check9 §4 で文を確かめたものだけ
_GERRIT_CORE = [re.compile(p) for p in (
    r"^Uploaded patch set ",
    r"^Commit message was updated",
    r"^Patch Set \d+ was rebased",
    r"^Published edit on patch set ",
    r"^Cherry Picked",
    r"^Change has been successfully merged",
    r"^Change has been successfully cherry-picked(?: as |\s*$)",   # "to the staging branch." は Qt の別の文（as のない形は未確認）
    r"^Change has been successfully rebased and submitted as ",
    r"^Change has been successfully pushed",
    r"^Abandoned",
    r"^Restored",
    r"^Created a revert of this change as ",
    r"^Set Work In Progress",
    r"^Set Ready For Review",
    r"^Reverted",
    r"^Topic set to ",
    r"^Topic changed from ",
    r"^Topic .+ removed$",
    r"^Removed the following votes:",
    r"^Removed [A-Za-z][\w-]*[+-]\d+ by ",
)]
# Qt のプラグインと Qt の古い改造版の文（Qt のホストだけ）。source_check8・source_check9 §1・§2
_QT = [re.compile(p) for p in (
    r"^Staged for CI",
    r"^Added to build ",
    r"^Merge conflict in staging branch",
    r"^Unstaged",
    r"^Change merged into branch '",
    r"^Precheck requested with params ",
    r"^Deferred",
    r"^Reopened",
    r"^Assigned to staging queue, waiting for promotion to CI",
    r"^Change has been successfully cherry-picked to the staging branch as ",
    r"^Change has been successfully merged into the staging branch\.",
    r"^Your change could not be merged due to a path conflict\.",
)]
# 後ろに操作した人の理由の文が続きうる記録（§3.2）
_WITH_REASON = re.compile(r"^(Abandoned|Restored|Deferred|Reopened)")


def _first_line_and_rest(message: dict) -> tuple[str, str]:
    text = str(message.get("message") or "")
    first, _, rest = text.partition("\n")
    return first.strip(), rest.strip()


def is_auto_record(message: dict, host: str) -> bool:
    """自動の記録か（§3.1。印のないものも含む）。理由の文が続く放棄・復活・後回し・再開は False（§3.2）。

    1 行目の前に付く `Patch Set N: ` は、Gerrit 本体の文に照らすときだけ外す。Qt の文は Qt のホストだけに、1 行目をそのまま当てる
    （2026-10-16 改めた。前置き付きの形、例 "Patch Set N: Deferred" は出どころ不明なので人のメッセージのまま）。
    出どころを確かめられなかった文は自動の記録としない（人のメッセージのまま）。
    """
    first, rest = _first_line_and_rest(message)
    body = _PS_PREFIX.sub("", first)
    if _WITH_REASON.match(body) and rest:
        return False                                   # 理由の文がある（§3.2）
    tag = message.get("tag")
    if isinstance(tag, str) and tag.startswith("autogenerated:"):
        return True
    if not message.get("author"):
        return True                                    # 書いた人がいない＝Gerrit そのもの
    if any(p.match(body) for p in _GERRIT_CORE):
        return True
    return host == QT_HOST and any(p.match(first) for p in _QT)


# ── 投票（pretrained_encoders/design.md §13.2。2026-10-16 追加） ─────────
# 1 行目の数字の形（例 "Patch Set 3: Code-Review+2 Verified-1"）。"-Code-Review"（取り消し）は投票として読まない
_VOTE_RE = re.compile(r"(?<![\w-])([A-Z][A-Za-z-]*)([+-]\d+)\b")
# 古い形式の投票（Gerrit の既定の文だけ。source_check9 §6）。各プロジェクト独自の文は読まない
OLD_VOTE_TEXTS = {
    "Looks good to me, approved": ("Code-Review", 2),
    "Looks good to me, but someone else must approve": ("Code-Review", 1),
    "No score": None,
    "I would prefer that you didn't submit this": ("Code-Review", -1),
    "I would prefer this is not merged as is": ("Code-Review", -1),
    "Do not submit": ("Code-Review", -2),
    "This shall not be merged": ("Code-Review", -2),
    "Verified": ("Verified", 1),
    "Fails": ("Verified", -1),
}


def votes_of(message: dict) -> list[tuple[str, int]]:
    """1 行目の投票（名前, 値）。数字の形と、古い形式の既定の文の読み替え。自動の記録の中の投票も返す。"""
    first, _rest = _first_line_and_rest(message)
    votes = [(lab, int(val)) for lab, val in _VOTE_RE.findall(first) if lab != "Patch"]
    if votes:
        return votes
    m = _PS_PREFIX.match(first)
    if not m:
        return []
    for part in first[m.end():].split(";"):
        hit = OLD_VOTE_TEXTS.get(part.strip().rstrip("."))
        if hit:
            votes.append(hit)
    return votes
